#!/usr/bin/env bash
# ==============================================================================
# SentinelBash - Forensic Timeline & Incident Dossier Compiler
# ==============================================================================
set -euo pipefail

CURRENT_SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
# shellcheck disable=SC1091
source "${CURRENT_SCRIPT_DIR}/common.sh"
load_config
init_sentinel_dirs

# Generate Incident ID if not provided
generate_incident_id() {
    echo "INC-$(date +%Y%m%d)-$(head -c 4 /dev/urandom 2>/dev/null | xxd -p 2>/dev/null || date +%s | tail -c 5)"
}

# Compile forensic dossier
# Arguments:
# $1: Incident ID
# $2: Attacker IP
# $3: Attack Vector (SSH_BRUTE_FORCE, WEB_EXPLOIT_SCAN, PRIV_ESC_ANOMALY, MANUAL)
# $4: Severity (CRITICAL, HIGH, MEDIUM, LOW)
# $5: Event Count
# $6: Raw Log Excerpts (optional / piped)
compile_timeline() {
    local inc_id="$1"
    local attacker_ip="$2"
    local vector="${3:-UNKNOWN_VECTOR}"
    local severity="${4:-HIGH}"
    local count="${5:-1}"
    local description="${6:-Automated security containment triggered by threshold breach.}"
    
    local md_file="${SENTINEL_INCIDENT_DIR}/${inc_id}.md"
    local json_file="${SENTINEL_INCIDENT_DIR}/${inc_id}.json"
    local hostname
    hostname="$(hostname 2>/dev/null || echo "linux-host")"
    local timestamp_iso
    timestamp_iso="$(get_timestamp)"
    local epoch_now
    epoch_now="$(get_epoch)"
    local driver
    driver="$(detect_netfilter_driver)"

    log_info "Compiling forensic incident dossier for ${inc_id} (Target: ${attacker_ip})..."

    # Collect recent normalized log lines related to this attacker IP
    local evidence_lines=""
    if [[ -f "${SENTINEL_LOG_DIR}/normalized.log" ]]; then
        evidence_lines="$(grep "|${attacker_ip}|" "${SENTINEL_LOG_DIR}/normalized.log" 2>/dev/null | tail -n 25 || true)"
    fi

    # Synchronize evidence records into incident_events table
    if [[ -f "${CURRENT_SCRIPT_DIR}/db.sh" && -n "$evidence_lines" ]]; then
        while IFS='|' read -r ev_epoch ev_svc ev_ip ev_type ev_details || [[ -n "$ev_epoch" ]]; do
            [[ -z "$ev_epoch" || -z "$ev_ip" ]] && continue
            "${CURRENT_SCRIPT_DIR}/db.sh" insert-event "$inc_id" "$ev_svc" "$ev_details" "{\"type\":\"${ev_type}\",\"ip\":\"${ev_ip}\"}" >/dev/null 2>&1 || true
        done <<< "$evidence_lines"
    fi

    # 1. Author Markdown Dossier
    cat <<EOF > "$md_file"
# Forensic Incident Report: ${inc_id}

| Parameter | Value |
| :--- | :--- |
| **Incident ID** | \`${inc_id}\` |
| **Timestamp (UTC)** | \`${timestamp_iso}\` |
| **Incident Status** | **CONTAINED** |
| **Severity Tier** | \`${severity}\` |
| **Attack Vector** | \`${vector}\` |
| **Attacker Source IP** | \`${attacker_ip}\` |
| **Target Hostname** | \`${hostname}\` |
| **Enforcement Engine** | \`${driver}\` (\`${IPTABLES_CHAIN}\` DROP) |
| **Event Breach Count** | ${count} events |

---

## 1. Executive Incident Summary
At **${timestamp_iso}**, the SentinelBash automated detection engine identified anomalous activity matching the **${vector}** heuristic rule. An aggressive inbound attack sequence originated from host **${attacker_ip}**, exceeding configured defensive thresholds (${count} violations). 

Pursuant to automated SOAR response policies, an immediate kernel netfilter isolation rule was injected to neutralize further lateral movement or credential compromise.

---

## 2. Chronological Attack Timeline & Forensic Telemetry

\`\`\`text
${evidence_lines:-No preceding raw logs captured in normalized log buffer.}
\`\`\`

---

## 3. Automated Containment Actions Taken
1. **Source IP Whitelist Verification:** Checked against \`whitelist.conf\`. Confirmed candidate is not protected infrastructure.
2. **Netfilter Packet Quarantine:**
   - Command: \`iptables -I ${IPTABLES_CHAIN} -s ${attacker_ip} -j DROP -m comment --comment "${IPTABLES_TAG_PREFIX}:${inc_id}"\`
   - Driver Status: Active (\`${driver}\`)
3. **Audit Ledger Update:** Event appended to Sentinel active bans registry and SQLite telemetry store.

---

## 4. Recommended Tier-2 Analyst Playbook
- [ ] Query external threat intelligence (AbuseIPDB, VirusTotal, Shodan) for reputation history on \`${attacker_ip}\`.
- [ ] Inspect \`/var/log/auth.log\` for any successful logins from \`${attacker_ip}\` prior to mitigation.
- [ ] Validate endpoint integrity and check for unauthorized daemon spawns or crontab modifications.
- [ ] If legitimate user lockout occurred, invoke: \`sentinel unban ${attacker_ip}\`.

---
*Report automatically generated by SentinelBash v1.0.0 — Zero-Bloat Linux SOC Automation Engine.*
EOF

    # 2. Author JSON Dossier
    cat <<EOF > "$json_file"
{
  "incident_id": "${inc_id}",
  "timestamp": "${timestamp_iso}",
  "epoch": ${epoch_now},
  "status": "CONTAINED",
  "severity": "${severity}",
  "attack_vector": "${vector}",
  "attacker_ip": "${attacker_ip}",
  "target_host": "${hostname}",
  "netfilter_driver": "${driver}",
  "event_count": ${count},
  "summary": "${description}",
  "markdown_dossier": "${md_file}"
}
EOF

    log_success "Forensic dossier written: ${md_file}"
    echo "$md_file"
}

# CLI Dispatcher
case "${1:-}" in
    generate|compile)
        shift
        compile_timeline "$@"
        ;;
    *)
        echo "Usage: $0 generate <INC_ID> <ATTACKER_IP> <VECTOR> <SEVERITY> <COUNT> [DESCRIPTION]"
        exit 1
        ;;
esac
